#!/usr/bin/env node
// Regenerates js/players.js — season-to-date half-PPR stats for every rostered player.
// Source: Sleeper's public stats API (season totals + one request per played week). Usage:  node tools/build-players.js
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
global.window = {};
require(path.join(ROOT, 'js', 'data.js'));
const B = window.BROOKDALE, S = B.season;
const POS = ['QB', 'RB', 'WR', 'TE', 'K', 'DEF'];
const qs = 'season_type=regular&' + POS.map((p) => 'position[]=' + p).join('&') + '&order_by=pts_half_ppr';
const get = async (url) => { const r = await fetch(url, { headers: { 'user-agent': 'Mozilla/5.0' } }); if (!r.ok) throw new Error(r.status + ' ' + url); return r.json(); };
const norm = (n) => n.toLowerCase().replace(/[.'’]/g, '').replace(/\s+(jr|sr|ii|iii|iv)$/, '').replace(/\s+/g, ' ').trim();
const r2 = (x) => Math.round((x || 0) * 100) / 100;
const pick = (st, keys) => { const o = {}; keys.forEach((k) => { if (st[k] != null && st[k] !== 0) o[k] = r2(st[k]); }); return o; };
const LINE = {
  QB: ['pass_cmp', 'pass_att', 'pass_yd', 'pass_td', 'pass_int', 'rush_att', 'rush_yd', 'rush_td', 'fum_lost'],
  RB: ['rush_att', 'rush_yd', 'rush_td', 'rec_tgt', 'rec', 'rec_yd', 'rec_td', 'fum_lost'],
  WR: ['rec_tgt', 'rec', 'rec_yd', 'rec_td', 'rush_att', 'rush_yd', 'rush_td', 'fum_lost'],
  TE: ['rec_tgt', 'rec', 'rec_yd', 'rec_td', 'fum_lost'],
  K: ['fgm', 'fga', 'fgm_lng', 'fgm_50p', 'xpm', 'xpa'],
  DEF: ['pts_allow', 'yds_allow', 'sack', 'int', 'fum_rec', 'def_td', 'def_st_td', 'safe', 'blk_kick'],
};

(async () => {
  const season = await get('https://api.sleeper.com/stats/nfl/' + S.year + '?' + qs);
  const weeks = [];
  for (let w = 1; w <= S.weeksPlayed; w++) weeks.push(await get('https://api.sleeper.com/stats/nfl/' + S.year + '/' + w + '?' + qs));
  const rows = season.filter((r) => r.player && POS.includes(r.player.position));
  // position ranks by total half-PPR points (computed here so they are consistent with the totals shown)
  const posRank = {};
  POS.forEach((p) => rows.filter((r) => r.player.position === p).sort((a, b) => (b.stats.pts_half_ppr || 0) - (a.stats.pts_half_ppr || 0)).forEach((r, i) => { posRank[r.player_id] = i + 1; }));
  const byKey = new Map();
  rows.forEach((r) => {
    const p = r.player; const full = p.position === 'DEF' ? 'DEF:' + String(r.team || p.team || r.player_id).toUpperCase() : norm(p.first_name + ' ' + p.last_name) + ':' + p.position;
    const prev = byKey.get(full); if (!prev || (r.stats.pts_half_ppr || 0) > (prev.stats.pts_half_ppr || 0)) byKey.set(full, r);
  });
  const weekById = weeks.map((arr) => { const m = new Map(); arr.forEach((r) => m.set(r.player_id, r)); return m; });
  const out = {}; const missing = [];
  Object.entries(S.rosters).forEach(([slug, ro]) => ro.starters.concat(ro.bench).forEach((pl) => {
    const key = pl.pos === 'DEF' ? 'DEF:' + pl.team.toUpperCase() : norm(pl.name) + ':' + pl.pos;
    const r = byKey.get(key);
    if (!r) { missing.push(slug + ' / ' + pl.name + ' (' + pl.pos + ', ' + pl.team + ')'); return; }
    const st = r.stats; const gp = st.gp || 0; const pts = r2(st.pts_half_ppr);
    out[pl.name] = {
      id: r.player_id, pos: pl.pos, team: pl.team, gp, pts, ppg: gp ? r2(pts / gp) : 0, posRank: posRank[r.player_id],
      weeks: weekById.map((m) => { const x = m.get(r.player_id); return x && x.stats && x.stats.gp > 0 ? r2(x.stats.pts_half_ppr) : null; }),
      line: pick(st, LINE[pl.pos]),
    };
  }));
  const header = '// ============================================================================\n' +
    '//  GENERATED by tools/build-players.js — do not hand-edit; re-run the script instead.\n' +
    '//  Season-to-date stats for every rostered player, weeks 1-' + S.weeksPlayed + ' of ' + S.year + ' (Sleeper stats, half-PPR scoring).\n' +
    '//  PLAYERS.byName[<name as in data.js rosters>] = { id, pos, team, gp, pts, ppg, posRank, weeks[pts per week | null = did not play], line{raw stat totals} }\n' +
    '//  line keys — QB: pass_cmp pass_att pass_yd pass_td pass_int rush_att rush_yd rush_td fum_lost · RB/WR/TE: rush_att rush_yd rush_td rec_tgt rec rec_yd rec_td fum_lost\n' +
    '//              K: fgm fga fgm_lng fgm_50p xpm xpa · DEF: pts_allow yds_allow sack int fum_rec def_td def_st_td safe blk_kick   (zero values are omitted)\n' +
    '// ============================================================================\n';
  const body = Object.keys(out).map((n) => '  ' + JSON.stringify(n) + ': ' + JSON.stringify(out[n])).join(',\n');
  fs.writeFileSync(path.join(ROOT, 'js', 'players.js'), header + 'window.PLAYERS = { season: ' + S.year + ', throughWeek: ' + S.weeksPlayed + ', scoring: "half-PPR", byName: {\n' + body + '\n} };\n');
  console.log('players written:', Object.keys(out).length, '| missing:', missing.length); missing.forEach((m) => console.log('  MISSING', m));
})().catch((e) => { console.error(e); process.exit(1); });
